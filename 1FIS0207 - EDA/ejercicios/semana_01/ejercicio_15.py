"""La ciudad de Ica está a una distancia de 600 Km de Lima. Determine cuánto demorará un auto viajando a una velocidad de 100km/h. ¿Y a 80km/h?"""

distancia = 600
velocidad_1 = 100
velocidad_2 = 80

tiempo1 = distancia / velocidad_1
tiempo2 = distancia / velocidad_2

print(
    f"Con una velocidad de {velocidad_1}km/h tomaria el tiempo de {tiempo1}h desde Ica a Lima"
)
print(
    f"Con una velocidad de {velocidad_2}km/h tomaria el tiempo de {tiempo2}h desde Ica a Lima"
)
